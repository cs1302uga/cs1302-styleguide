package edu.uga.cs1302.example;

/**
 * Invalid right curly brace placement.
 */
public class InvalidRightCurly {

    /**
     * Check value with else on new line.
     *
     * @param a input
     */
    public void check(int a) {
        if (a > 0) {
            a++;
        }
        else {
            a--;
        } // if
    } // check

} // InvalidRightCurly
