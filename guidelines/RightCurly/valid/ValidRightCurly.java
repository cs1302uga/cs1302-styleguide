package edu.uga.cs1302.example;

/**
 * Valid right curly brace placement.
 */
public class ValidRightCurly {

    /**
     * Check value.
     *
     * @param a input
     */
    public void check(int a) {
        if (a > 0) {
            a++;
        } else {
            a--;
        } // if
    } // check

} // ValidRightCurly
