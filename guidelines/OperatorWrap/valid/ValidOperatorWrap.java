package edu.uga.cs1302.example;

/**
 * Valid operator wrapping.
 */
public class ValidOperatorWrap {

    /**
     * Compute sum.
     *
     * @param a first
     * @param b second
     * @param c third
     * @return sum
     */
    public int sum(int a, int b, int c) {
        int total = a + b
            + c;
        return total;
    } // sum

} // ValidOperatorWrap
