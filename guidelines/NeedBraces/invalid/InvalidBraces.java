package edu.uga.cs1302.example;

/**
 * Invalid missing curly braces.
 */
public class InvalidBraces {

    /**
     * Increment.
     *
     * @param x input
     * @return result
     */
    public int increment(int x) {
        if (x > 0)
            x++;
        return x;
    } // increment

} // InvalidBraces
