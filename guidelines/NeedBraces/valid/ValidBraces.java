package edu.uga.cs1302.example;

/**
 * Valid explicit curly braces.
 */
public class ValidBraces {

    /**
     * Increment.
     *
     * @param x input
     * @return result
     */
    public int increment(int x) {
        if (x > 0) {
            x++;
        } // if
        return x;
    } // increment

} // ValidBraces
