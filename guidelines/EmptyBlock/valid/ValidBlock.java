package edu.uga.cs1302.example;

/**
 * Valid non-empty block.
 */
public class ValidBlock {

    /**
     * Compute.
     *
     * @param x input
     * @return result
     */
    public int compute(int x) {
        if (x > 0) {
            x++;
        } // if
        return x;
    } // compute

} // ValidBlock
